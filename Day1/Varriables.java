public class Varriables{
    public static void main(String[]args){

        // learning avout varriables in java
        int a=10; //here is the varriable that specifies the value of a

        String name="Abhi"; //here is the varriable that specifies the value of name

        float b=10.5f; //here is the varriable that specifies the value of b

        double c=11.5;//here is the varriable that specifies the value of c 

        //printing the values of the varriables

        System.out.println("a: "+a);

        System.out.println("name: "+name);

        System.out.println("b: "+b);

        System.out.println("c: "+c);
    }

}