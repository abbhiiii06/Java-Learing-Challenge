//Datattypes in java 
public class DataTypes{
    public static void main(String[]args){
        int a=10;  //Integer Data type
        String name="Abhi"; //String Data type
        float b=10.0f; //Float Data type
        double c=11.5; //Double Data type
        long d=1000000L; //Long Data type
        boolean e=true; //Boolean Data type
        char f='A'; //Character Data type
        short g=100; //Short Data type

        //prinnting the values of the datatypes

        System.out.println("Integer: "+a);
        System.out.println("String: "+name);
        System.out.println("Float: "+b);
        System.out.println("Double: "+c);
        System.out.println("Long: "+d);
        System.out.println("Boolean: "+e);
        System.out.println("Character: "+f);
        System.out.println("Short: "+g);

        //printing the range of the datatypes

        System.out.println("Range of Integer: "+Integer.MIN_VALUE+" to "+Integer.MAX_VALUE);
        System.out.println("Range of Float: "+Float.MIN_VALUE+" to "+Float.MAX_VALUE);
        System.out.println("Range of Double: "+Double.MIN_VALUE+" to "+Double.MAX_VALUE);
        System.out.println("Range of Long: "+Long.MIN_VALUE+" to "+Long.MAX_VALUE);
        System.out.println("Range of Boolean: true to false");
        System.out.println("Range of Character: "+Character.MIN_VALUE+" to "+Character.MAX_VALUE);
        System.out.println("Range of Short: "+Short.MIN_VALUE+" to "+Short.MAX_VALUE);
    }
}

        